interface Props {
  channel: Channel
  token: string
  ws: GanderWS
}

export default function ChannelView({ channel, token, ws }: Props) {
  const [messages, setMessages] = useState<Message[]>([])
  const [input, setInput] = useState('')
  const [loading, setLoading] = useState(true)
  const bottomRef = useRef<HTMLDivElement>(null)
  const textareaRef = useRef<HTMLTextAreaElement>(null)

  function resize() {
    const el = textareaRef.current
    if (!el) return
    el.style.height = 'auto'
    el.style.height = `${el.scrollHeight}px`
  }

  // Load history and join channel whenever the active channel changes
  useEffect(() => {
    setLoading(true)
    setMessages([])

    api.getMessages(token, channel.id).then(msgs => {
      setMessages(msgs)
      setLoading(false)
    })

    ws.send({ type: 'channel:join', payload: { channelId: channel.id } })

    return () => {
      ws.send({ type: 'channel:leave', payload: { channelId: channel.id } })
    }
  }, [channel.id, token, ws])

  // Subscribe to incoming WS events
  useEffect(() => {
    return ws.on(event => {
      if (event.type === 'message:new' && event.payload.channelId === channel.id) {
        setMessages(prev => [...prev, event.payload])
      }
      if (event.type === 'message:edited' && event.payload.channelId === channel.id) {
        setMessages(prev => prev.map(m => m.id === event.payload.id ? event.payload : m))
      }
      if (event.type === 'message:deleted' && event.payload.channelId === channel.id) {
        setMessages(prev => prev.filter(m => m.id !== event.payload.id))
      }
    })
  }, [channel.id, ws])

  // Scroll to bottom when new messages arrive
  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth' })
  }, [messages])

  function send() {
    if (!input.trim()) return
    ws.send({ type: 'message:send', payload: { channelId: channel.id, content: input.trim() } })
    setInput('')
    if (textareaRef.current) textareaRef.current.style.height = 'auto'
  }

  function handleKeyDown(e: React.KeyboardEvent<HTMLTextAreaElement>) {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault()
      send()
    }
  }

  return (
    <div className={styles.root}>
      <div className={styles.watermark} aria-hidden="true">
        <pre className={styles.watermarkLogo}>{LOGO}</pre>
      </div>

      <header className={styles.header}>
        <span className={styles.channelName}># {channel.name}</span>
      </header>

      <div className={styles.messages}>
        {loading && <p className={styles.status}>loading...</p>}
        {!loading && messages.length === 0 && (
          <p className={styles.status}>no messages yet — say something</p>
        )}
        {messages.map((msg, i) => {
          const prev = messages[i - 1]
          const grouped = prev && prev.authorId === msg.authorId &&
            (new Date(msg.createdAt).getTime() - new Date(prev.createdAt).getTime()) < 5 * 60 * 1000

          return (
            <div key={msg.id} className={`${styles.message} ${grouped ? styles.grouped : ''}`}>
              {!grouped && (
                <div className={styles.meta}>
                  <span className={styles.author}>{msg.authorName}</span>
                  <span className={styles.time}>{formatTime(msg.createdAt)}</span>
                </div>
              )}
              <p className={styles.content}>{msg.content}</p>
            </div>
          )
        })}
        <div ref={bottomRef} />
      </div>

      <form className={styles.inputBar} onSubmit={e => { e.preventDefault(); send() }}>
        <span className={styles.prompt}>&gt;</span>
        <textarea
          ref={textareaRef}
          className={styles.input}
          placeholder={`message #${channel.name}`}
          value={input}
          rows={1}
          onChange={e => { setInput(e.target.value); resize() }}
          onKeyDown={handleKeyDown}
          autoComplete="off"
          autoFocus
        />
      </form>
    </div>
  )
}

function formatTime(iso: string): string {
  const d = new Date(iso)
  return d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
}
